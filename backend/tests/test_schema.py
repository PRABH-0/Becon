def test_schema_constraints_and_cascades(sqlite_engine):
    """Acceptance criterion 3: constraints, CHECKs, and cascade / SET NULL behavior."""
    engine, _ = sqlite_engine
    Session = sessionmaker(bind=engine)
    db = Session()

    try:
        # 1. Unique raw_items(source_id, url_hash)
        source = Source(
            slug="test-source",
            name="Test Source",
            site_url="https://example.com",
            feed_url="https://example.com/feed",
            type="rss",
            trust_tier=1,
            fetch_interval_minutes=60,
            enabled=True,
            language="en",
        )
        db.add(source)
        db.commit()

        item1 = RawItem(
            source_id=source.id,
            url="https://example.com/post1",
            url_hash="hash123",
            title="Post 1",
            language="en",
            status="new",
        )
        db.add(item1)
        db.commit()

        item2 = RawItem(
            source_id=source.id,
            url="https://example.com/post1-duplicate",
            url_hash="hash123",  # same hash for same source
            title="Duplicate Post",
            language="en",
            status="new",
        )
        db.add(item2)
        with pytest.raises(IntegrityError):
            db.commit()
        db.rollback()

        # 2. Unique topic_aliases.alias
        topic = FocusTopic(slug="react-test", name="React Test", kind="technology")
        db.add(topic)
        db.commit()

        alias1 = TopicAlias(topic_id=topic.id, alias="reactjs")
        db.add(alias1)
        db.commit()

        alias2 = TopicAlias(topic_id=topic.id, alias="reactjs")
        db.add(alias2)
        with pytest.raises(IntegrityError):
            db.commit()
        db.rollback()

        # 3. CHECK on severity_score (0-100)
        invalid_event = Event(
            canonical_title="Invalid Severity Event",
            canonical_url="https://example.com/event",
            category="release",
            severity_score=150,  # Invalid: > 100
            is_breaking=False,
            status="open",
        )
        db.add(invalid_event)
        with pytest.raises(IntegrityError):
            db.commit()
        db.rollback()

        # Valid event
        event_obj = Event(
            canonical_title="Valid Event",
            canonical_url="https://example.com/valid",
            category="release",
            severity_score=85,
            is_breaking=True,
            status="open",
        )
        db.add(event_obj)
        db.commit()

        # 4. Create card
        card_obj = Card(
            event_id=event_obj.id,
            what_happened=["Point 1", "Point 2"],
            why_it_matters="Matters a lot",
            how_it_affects_you="Affects your setup",
            action_type="apply",
            action_guidance="Upgrade packages",
            source_url="https://example.com/valid",
            source_text_hash="abc123hash",
            model_name="gemini-2.0-flash",
            prompt_version="1.0",
            status="published",
        )
        db.add(card_obj)
        db.commit()

        # 5. User creation and unique saved_cards
        user = UserProfile(name="Test User", email="testuser@example.com")
        db.add(user)
        db.commit()

        saved1 = SavedCard(user_id=user.id, card_id=card_obj.id)
        db.add(saved1)
        db.commit()

        saved2 = SavedCard(user_id=user.id, card_id=card_obj.id)
        db.add(saved2)
        with pytest.raises(IntegrityError):
            db.commit()
        db.rollback()

        # 6. CHECK on card_feedback.value (-1 or 1)
        invalid_feedback = CardFeedback(user_id=user.id, card_id=card_obj.id, value=5)
        db.add(invalid_feedback)
        with pytest.raises(IntegrityError):
            db.commit()
        db.rollback()

        valid_feedback = CardFeedback(user_id=user.id, card_id=card_obj.id, value=1)
        db.add(valid_feedback)

        # 7. User Follow
        follow = UserFollow(user_id=user.id, source_id=source.id)
        db.add(follow)
        db.commit()

        # 8. Test user deletion cascades: removes follows, saved_cards, feedback
        db.delete(user)
        db.commit()

        assert db.query(SavedCard).filter(SavedCard.card_id == card_obj.id).count() == 0
        assert db.query(CardFeedback).filter(CardFeedback.card_id == card_obj.id).count() == 0
        assert db.query(UserFollow).filter(UserFollow.source_id == source.id).count() == 0

        # 9. Test deleting a source does NOT delete events
        # Link raw item to event
        item1.event_id = event_obj.id
        db.commit()

        db.delete(source)
        db.commit()

        # Event remains intact!
        assert db.query(Event).filter(Event.id == event_obj.id).count() == 1

    finally:
        db.close()


def test_duplicate_email_migration():
    """Acceptance criterion 2 & test 4: deduplicate emails during 0002 migration."""
    temp_file = tempfile.NamedTemporaryFile(suffix=".db", delete=False)
    temp_path = temp_file.name
    temp_file.close()
    db_url = f"sqlite:///{temp_path}"

    cfg = get_alembic_config(db_url)

    try:
        # 1. Migrate only to 0001 (baseline)
        command.upgrade(cfg, "0001")

        engine = create_engine(db_url)
        with engine.begin() as conn:
            # Insert duplicate emails with different cases
            conn.execute(
                text("INSERT INTO user_profiles (id, name, email, auth_provider) VALUES (1, 'User One', 'User@Example.Com', 'local')")
            )
            conn.execute(
                text("INSERT INTO user_profiles (id, name, email, auth_provider) VALUES (2, 'User Two', 'user@example.com', 'google')")
            )
            conn.execute(
                text("INSERT INTO user_profiles (id, name, email, auth_provider) VALUES (3, 'Guest User', 'guest_123@guest.local', 'guest')")
            )

        # 2. Run 0002 migration
        command.upgrade(cfg, "head")

        with engine.connect() as conn:
            rows = conn.execute(
                text("SELECT id, name, email, is_anonymous FROM user_profiles ORDER BY id")
            ).fetchall()

            # Must have merged 1 duplicate, leaving exactly 2 rows
            assert len(rows) == 2, f"Expected 2 rows after dedup, got {len(rows)}"
            assert rows[0][0] == 1, "Expected lowest id (1) to be preserved"
            assert rows[0][2] == "user@example.com", f"Expected lowercase email, got {rows[0][2]}"
            assert rows[1][0] == 3, "Expected guest user id 3 to be preserved"
            assert rows[1][3] == 1, "Expected guest user is_anonymous=True"

        engine.dispose()
    finally:
        if os.path.exists(temp_path):
            try:
                os.remove(temp_path)
            except Exception:
                pass


def test_seed_idempotency_and_alias_resolution(sqlite_engine):
    """Acceptance criterion 5: seed runs twice with identical results; aliases resolve."""
    engine, _ = sqlite_engine
    Session = sessionmaker(bind=engine)
    db = Session()

    try:
        # First run
        run1 = seed(db)
        # Second run
        run2 = seed(db)

        assert run1 == run2, f"Seed run 1 ({run1}) != run 2 ({run2})"
        assert run1["professions"] == 2
        assert run1["topics"] >= 40

        # Verify nextjs alias resolves to Next.js topic
        alias = db.query(TopicAlias).filter(TopicAlias.alias == "nextjs").first()
        assert alias is not None, "Alias 'nextjs' not found in database"
        assert alias.topic.name == "Next.js"
        assert alias.topic.slug == "nextjs"

        # Verify profession links
        dev_prof = db.query(Profession).filter(Profession.slug == "software-development").first()
        assert len(dev_prof.profession_topics) >= 30
    finally:
        db.close()


def test_safe_user_creation_paths_and_races(sqlite_engine):
    """Acceptance criterion 6: register, sync, and guest never create dupes or 500 on races."""
    engine, _ = sqlite_engine
    TestingSessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=engine)

    def override_get_db():
        db = TestingSessionLocal()
        try:
            yield db
        finally:
            db.close()

    app.dependency_overrides[get_db] = override_get_db
    client = TestClient(app)

    try:
        # 1. Register: case-insensitive get-or-create
        reg_payload = {"email": "DevUser@Example.Com", "password": "password123!", "name": "Dev User"}
        res1 = client.post("/api/register", json=reg_payload)
        assert res1.status_code == 200, res1.text
        assert "access_token" in res1.json()

        # Re-registering with different case returns existing user without error
        res2 = client.post("/api/register", json={"email": "devuser@example.com", "password": "differentpassword"})
        assert res2.status_code == 200, res2.text
        assert "access_token" in res2.json()

        # 2. Supabase sync: get-or-create
        sync_payload = {
            "email": "SYNCUSER@example.COM",
            "name": "Sync User",
            "picture_url": "https://example.com/avatar.jpg",
            "provider": "google",
        }
        res3 = client.post("/api/auth/supabase-sync", json=sync_payload)
        assert res3.status_code == 200, res3.text

        # Calling sync again with same email in lowercase
        res4 = client.post("/api/auth/supabase-sync", json={"email": "syncuser@example.com", "name": "Updated Name"})
        assert res4.status_code == 200, res4.text

        # 3. Guest auth
        res5 = client.post("/api/auth/guest")
        assert res5.status_code == 200, res5.text
        assert "access_token" in res5.json()

        # 4. Verify user counts in DB
        db = TestingSessionLocal()
        users = db.query(UserProfile).all()
        user_emails = [u.email for u in users]
        # Should have exactly 1 devuser, 1 syncuser, 1 guestuser
        assert "devuser@example.com" in user_emails
        assert "syncuser@example.com" in user_emails
        assert len(user_emails) == len(set(user_emails)), "Duplicate emails found in database!"
        db.close()

    finally:
        app.dependency_overrides.pop(get_db, None)


